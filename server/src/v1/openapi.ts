function jsonSchema(schema: z.ZodType): Record<string, unknown> {
  try {
    return z.toJSONSchema(schema, { io: "input", unrepresentable: "any" }) as Record<string, unknown>;
  } catch {
    return { type: "object" };
  }
}

interface Layer {
  route?: { path: string | string[]; methods: Record<string, boolean>; stack: Array<{ handle: Parameters<typeof permissionMeta>[0] }> };
}

export function buildOpenApi(router: Router, serverUrl = "/api/v1") {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const layer of (router as unknown as { stack: Layer[] }).stack) {
    if (!layer.route) continue;
    const rawPaths = Array.isArray(layer.route.path) ? layer.route.path : [layer.route.path];
    for (const raw of rawPaths) {
      const path = raw.replace(/:(\w+)/g, "{$1}");
      for (const method of Object.keys(layer.route.methods).filter((m) => layer.route!.methods[m] && m !== "_all")) {
        const handles = layer.route.stack.map((s) => s.handle);
        const secured = handles.includes(authenticate);
        const meta = handles.map(permissionMeta).filter(Boolean);
        const all = meta.flatMap((m) => m!.all ?? []);
        const any = meta.flatMap((m) => m!.any ?? []);
        const doc = DOCS[`${method.toUpperCase()} ${path}`];
        const params = [...path.matchAll(/\{(\w+)\}/g)].map((m) => ({ name: m[1], in: "path", required: true, schema: { type: "string" }, description: m[1] === "propertyId" ? "UUID or readable code (SR-PROP-000001)" : undefined }));
        const query = doc?.query ? jsonSchema(doc.query) : null;
        const queryParams = query && typeof query.properties === "object" ? Object.entries(query.properties as Record<string, unknown>).map(([name, schema]) => ({ name, in: "query", required: false, schema })) : [];
        const pagination = method === "get" && !/\{[^}]+\}$/.test(path) ? [{ name: "page", in: "query", schema: { type: "integer", minimum: 1, default: 1 } }, { name: "pageSize", in: "query", schema: { type: "integer", minimum: 1, maximum: 100, default: 20 } }, { name: "q", in: "query", schema: { type: "string", maxLength: 100 } }] : [];
        const permissionText = [all.length ? `Requires: ${all.join(", ")}` : "", any.length ? `Requires one of: ${any.join(", ")}` : ""].filter(Boolean).join(". ");
        (paths[path] ??= {})[method] = {
          tags: [path.split("/")[1] ?? "general"],
          summary: doc?.summary ?? `${method.toUpperCase()} ${path}`,
          description: [doc?.description, permissionText, secured ? "Resource scope (own / assigned / all) is enforced on the server." : "Public."].filter(Boolean).join("\n\n"),
          ...(secured ? { security: [{ firebaseIdToken: [] }] } : { security: [] }),
          parameters: [...params, ...queryParams, ...pagination],
          ...(doc?.body ? { requestBody: { required: true, content: { "application/json": { schema: jsonSchema(doc.body) } } } } : {}),
          ...(doc?.multipart
            ? { requestBody: { required: true, content: { "multipart/form-data": { schema: { type: "object", properties: Object.fromEntries(Object.entries(doc.multipart).map(([k, d]) => [k, { type: "string", description: d, ...(k === "files" || k === "file" ? { format: "binary" } : {}) }])) } } } } }
            : {}),
          responses: {
            "200": { description: "Success", content: { "application/json": { schema: { $ref: "#/components/schemas/Success" } } } },
            "400": { $ref: "#/components/responses/Error" },
            "401": { $ref: "#/components/responses/Error" },
            "403": { $ref: "#/components/responses/Error" },
            "404": { $ref: "#/components/responses/Error" },
            "409": { $ref: "#/components/responses/Error" },
            "429": { $ref: "#/components/responses/Error" },
          },
        };
      }
    }
  }
  return {
    openapi: "3.1.0",
    info: {
      title: "SafeRent API",
      version: "1.0.0",
      description: [
        "One API for Android, iOS and the Admin Panel. Never build platform-specific endpoints.",
        "",
        "**Authentication.** Sign in with Firebase Authentication (phone OTP for customers; email + password + email OTP for staff), then send `Authorization: Bearer <Firebase ID token>`. The server verifies the token (revocation checked) and loads the role and permissions from MySQL. Roles or owner ids sent by a client are ignored.",
        "",
        "**Headers.** `X-Client-Platform: ANDROID | IOS | ADMIN_PANEL` (recorded in audit logs), optional `X-Request-Id`, and `X-Firebase-AppCheck` when App Check is enforced.",
        "",
        "**Responses.** `{ success, message, data, meta }` on success; `{ success: false, message, errorCode, reason, data: null }` on error. Error codes: VALIDATION_ERROR (400, `details.issues` lists fields), UNAUTHENTICATED (401), SESSION_REQUIRED, FORBIDDEN (403), NOT_FOUND (404 — also returned for records outside your scope), CONFLICT (409 — duplicates, stale `version`), INVALID_STATE / PRECONDITION_FAILED (412), RATE_LIMITED (429), INTERNAL_ERROR (500).",
        "",
        "**Pagination.** `?page=1&pageSize=20` (max 100); `meta` returns page, pageSize, total, totalPages.",
        "",
        "**Disclosure values.** YES / NO / NOT_APPLICABLE / NOT_DISCLOSED. NOT_DISCLOSED never means NO.",
        "",
        "**Image upload flow.** Create the property → POST multipart files to /properties/{id}/images → photos are PENDING until a moderator approves the listing → approved photos of published listings are served by /files/property-images/{imageId} (always with the bearer token).",
        "",
        "**Property creation flow.** GET /property-types → POST /properties → PATCH (basic, location, `building` fields) → units / rooms & beds → utilities → policies → amenities → pricing → images & documents → GET /completeness → POST /submit → (moderator) POST /review → POST /publish.",
      ].join("\n"),
    },
    servers: [{ url: serverUrl }],
    components: {
      securitySchemes: { firebaseIdToken: { type: "http", scheme: "bearer", bearerFormat: "Firebase ID token" } },
      schemas: {
        Success: { type: "object", properties: { success: { const: true }, message: { type: "string" }, data: {}, meta: { type: ["object", "null"] } } },
        Error: { type: "object", properties: { success: { const: false }, message: { type: "string" }, errorCode: { type: "string" }, reason: { type: ["string", "null"] }, details: { type: "object" }, data: { type: "null" } } },
      },
      responses: { Error: { description: "Error", content: { "application/json": { schema: { $ref: "#/components/schemas/Error" } } } } },
    },
    paths,
  };
}

export function openApiHandler(router: Router) {
  let cached: unknown = null;
  return (_req: Request, res: Response) => {
    cached ??= buildOpenApi(router);
    res.locals.rawJson = true;
    res.json(cached);
  };
}

